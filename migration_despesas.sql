-- ============================================================
-- Cadastro de DESPESA (transacional): código sequencial automático,
-- fornecedor, unidade, centro de custo (units), tipo (expense_types),
-- valor e competência (ano/mês). Aditivo e idempotente.
-- ============================================================
BEGIN;

CREATE TABLE IF NOT EXISTS public.despesas (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  seq             bigint GENERATED BY DEFAULT AS IDENTITY,
  supplier_id     uuid REFERENCES public.suppliers(id),
  unidade_id      uuid REFERENCES public.unidades(id),
  unit_id         uuid REFERENCES public.units(id),          -- centro de custo
  expense_type_id uuid REFERENCES public.expense_types(id),  -- tipo (CAPEX/OPEX/OPEX OTC)
  value           numeric(14,2),
  year            int,
  month           int,
  notes           text,
  is_active       boolean NOT NULL DEFAULT true,
  created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS despesas_seq_uk ON public.despesas(seq);
CREATE INDEX IF NOT EXISTS idx_despesas_supplier ON public.despesas(supplier_id);
CREATE INDEX IF NOT EXISTS idx_despesas_unidade  ON public.despesas(unidade_id);

COMMIT;
